"""Generate deterministic GBK / Big5 / GB18030 lookup tables.

The runtime must not depend on the host's ICU tables: Node and browsers
disagree on a number of Big5/GBK slots (e.g. 0xA5BF is 文 in the Taiwan
standard but 正 in some ICU builds). We therefore compile the tables from
Python's codecs once and ship them as compact base64 assets.

Output: src/lib/encoding/tables-data.ts
"""
import base64
import json
import os
import struct

OUT = os.path.join(os.path.dirname(__file__), '..', 'src', 'lib', 'encoding', 'tables-data.ts')
TRAILS = [t for t in range(0x40, 0xFF) if t != 0x7F]
LEADS = list(range(0x81, 0xFF))


def build_two_byte(codec):
    slots = []
    for lead in LEADS:
        for trail in TRAILS:
            try:
                s = bytes([lead, trail]).decode(codec)
            except UnicodeDecodeError:
                s = None
            slots.append(ord(s) if s and len(s) == 1 else 0)
    raw = struct.pack(f'<{len(slots)}H', *slots)
    return base64.b64encode(raw).decode('ascii'), slots


def build_ranges():
    """GB18030 linear 4-byte mapping expressed as (pointer, codepoint) ranges."""
    ranges = []
    prev = None
    for pointer in range(0, 39420):
        b1 = pointer // 12600 + 0x81
        b2 = (pointer % 12600) // 1260 + 0x30
        b3 = (pointer % 1260) // 10 + 0x81
        b4 = pointer % 10 + 0x30
        try:
            s = bytes([b1, b2, b3, b4]).decode('gb18030')
            cp = ord(s) if s and len(s) == 1 else None
        except UnicodeDecodeError:
            cp = None
        if cp is None:
            prev = None
            continue
        if prev is None or cp - prev[1] != 1:
            ranges.append([pointer, cp])
        prev = [pointer, cp]
    prev = None
    for pointer in range(189000, 1237576):
        b1 = pointer // 12600 + 0x81
        b2 = (pointer % 12600) // 1260 + 0x30
        b3 = (pointer % 1260) // 10 + 0x81
        b4 = pointer % 10 + 0x30
        try:
            s = bytes([b1, b2, b3, b4]).decode('gb18030')
            if len(s) != 1:
                continue
            cp = ord(s)
        except UnicodeDecodeError:
            continue
        if prev is None or cp - prev[1] != 1:
            ranges.append([pointer, cp])
        prev = [pointer, cp]
    return ranges


gbk_b64, gbk_slots = build_two_byte('gbk')
big5_b64, big5_slots = build_two_byte('cp950')
ranges = build_ranges()

payload = {
    'leads': [LEADS[0], LEADS[-1]],
    'trails': [TRAILS[0], TRAILS[-1], 0x7F],
    'gbk': gbk_b64,
    'big5': big5_b64,
    'ranges': ranges,
}
ts = (
    '// AUTO-GENERATED by scripts/generate-encoding-tables.py — do not edit.\n'
    '// Two-byte GBK / Big5 (cp950) tables plus GB18030 four-byte ranges,\n'
    '// compiled from Python codecs for consistent behaviour in every host.\n'
    f'export const TWO_BYTE_LEAD_MIN = 0x{LEADS[0]:02x};\n'
    f'export const TWO_BYTE_LEAD_MAX = 0x{LEADS[-1]:02x};\n'
    f'export const TWO_BYTE_TRAIL_MIN = 0x{TRAILS[0]:02x};\n'
    f'export const TWO_BYTE_TRAIL_MAX = 0x{TRAILS[-1]:02x};\n'
    f'export const TWO_BYTE_TRAIL_GAP = 0x7f;\n'
    f'export const GBK_TABLE_B64 =\n  {json.dumps(gbk_b64)};\n'
    f'export const BIG5_TABLE_B64 =\n  {json.dumps(big5_b64)};\n'
    f'export const GB_FOUR_BYTE_RANGES: ReadonlyArray<readonly [number, number]> = {json.dumps(ranges)};\n'
)
os.makedirs(os.path.dirname(OUT), exist_ok=True)
with open(OUT, 'w', encoding='utf-8') as f:
    f.write(ts)
assigned_gbk = sum(1 for s in gbk_slots if s)
assigned_big5 = sum(1 for s in big5_slots if s)
print(f'wrote {OUT} ({os.path.getsize(OUT)} bytes); gbk {assigned_gbk} slots, big5 {assigned_big5} slots, {len(ranges)} ranges')
