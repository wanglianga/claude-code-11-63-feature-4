# Simplified→Traditional pairs let a Big5-decoded fragment be recognised by
# the same lexicon. We store both forms for each distinct character.
cross = {}
for w, _ in entries[:60000]:
    for ch in w:
        if not ('一' <= ch <= '鿿'):
            continue
    # (handled by char loop below)
raw_chars = [c for c in char_freq if '一' <= c <= '鿿']
for ch in raw_chars:
    t = s2t.convert(ch)
    if t != ch and len(t) == 1 and t not in char_freq:
        cross[t] = ch
for w in DRUG_TERMS:
    t = s2t.convert(w)
    for a, b in zip(w, t):
        if a != b and '一' <= b <= '鿿' and b not in char_freq:
            cross[b] = a

# Top characters only — a compact ranked list (rank ≈ frequency order).
ranked = [c for c, _ in char_freq.most_common(2600) if '一' <= c <= '鿿']
ranked_seen = set(ranked)
# Include every character from the pharma vocabulary plus traditional variants.
for w in DRUG_TERMS:
    for ch in w:
        if '一' <= ch <= '鿿' and ch not in ranked_seen:
            ranked.append(ch)
            ranked_seen.add(ch)
for t in cross:
    if t not in ranked_seen:
        ranked.append(t)
        ranked_seen.add(t)

chars = ''.join(ranked)
cross_pairs = ''.join(f'{t}{s}' for t, s in cross.items())
vocab = sorted({w for w, _ in entries if 2 <= len(w) <= 4 and all('一' <= c <= '鿿' for c in w)})
vocab = vocab[:16000]
terms = sorted({s2t.convert(w) for w in DRUG_TERMS} | set(DRUG_TERMS))

payload = {
    'chars': chars,
    'cross': cross_pairs,
    'vocab': '\n'.join(vocab),
    'terms': terms,
}
blob = json.dumps(payload, ensure_ascii=False, separators=(',', ':'))
ts = (
    '// AUTO-GENERATED by scripts/generate-lexicon.py — do not edit by hand.\n'
    '// Character ranks from jieba dict (MIT); simplified/traditional cross map\n'
    '// from OpenCC (Apache-2.0); pharma terms curated for this project.\n'
    f'export const LEXICON_BLOB: string = {json.dumps(blob, ensure_ascii=False)};\n'
)
os.makedirs(os.path.dirname(OUT), exist_ok=True)
with open(OUT, 'w', encoding='utf-8') as f:
    f.write(ts)
print('wrote', OUT, os.path.getsize(OUT), 'bytes;', len(chars), 'chars;', len(cross), 'cross;', len(vocab), 'vocab;', len(terms), 'terms')
