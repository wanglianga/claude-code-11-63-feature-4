import { describe, expect, it } from 'vitest';
import { runAnalysis } from '../src/lib/analysis/analyze';
import { buildCandidates } from '../src/lib/analysis/candidates';
import { segmentFile } from '../src/lib/analysis/segmenter';
import { DEFAULT_PARAMS } from '../src/lib/encoding/specs';
import { formatBytes } from '../src/lib/util/bytes';
import { encodeWith } from '../src/lib/encoding/codecs';
import { sampleBytes } from './setup';
import type { AnalysisParams } from '../src/types';

function analyze(name: string, patch: Partial<AnalysisParams> = {}) {
  const bytes = sampleBytes(name);
  return runAnalysis({
    bytes,
    digest: 'probe',
    params: { ...DEFAULT_PARAMS, ...patch },
    now: '2026-01-01T00:00:00.000Z',
  });
}

describe('mixed-encoding sample', () => {
  it('finds the GBK, Big5 and UTF-8 regions', () => {
    const bytes = sampleBytes('mixed-encoded-label.txt');
    const segs = segmentFile(bytes, DEFAULT_PARAMS);
    expect(segs.length).toBe(3);
    expect(segs.map((s) => s.hypothesis)).toEqual(['gb18030', 'big5', 'utf-8']);
    // The Big5 block starts at the 【不良反應】 heading, whose Big5 bytes we
    // locate with the project codec (the fixture is generated by the script).
    const heading = encodeWith('big5', '【不良反應】');
    if ('error' in heading) throw new Error(heading.error);
    const big5Heading = Buffer.from(bytes).indexOf(Buffer.from(heading.bytes));
    expect(big5Heading).toBeGreaterThan(0);
    expect(Math.abs(segs[1].start - big5Heading)).toBeLessThan(8);
    // Segments tile the file without gaps or overlaps.
    expect(segs[0].start).toBe(0);
    expect(segs[segs.length - 1].end).toBe(bytes.length);
    for (let i = 1; i < segs.length; i++) expect(segs[i].start).toBe(segs[i - 1].end);
  });

  it('recommends segmented diagnosis and explains why', () => {
    const bundle = analyze('mixed-encoded-label.txt');
    expect(bundle.recommendedStrategy).toBe('segmented');
    expect(bundle.segmented.metrics.distinctEncodings).toBeGreaterThan(1);
    expect(bundle.segmented.metrics.anomalyBytes).toBeLessThan(bundle.uniform.metrics.anomalyBytes);
    expect(bundle.recommendationRationale.join(' ')).toContain('编码');
  });

  it('keeps the uniform strategy at exactly one segment', () => {
    const bundle = analyze('mixed-encoded-label.txt');
    expect(bundle.uniform.segments).toHaveLength(1);
    expect(bundle.uniform.boundaryReviews).toHaveLength(0);
  });

  it('compares strategies along the dimensions the task names', () => {
    const bundle = analyze('mixed-encoded-label.txt');
    const metrics = bundle.comparisonRows.map((r) => r.metric);
    expect(metrics).toEqual(
      expect.arrayContaining(['区段数', '候选总数', '高风险边界', '不可解符号占位', '复核工作量（加权）']),
    );
  });
});

describe('mojibake sample', () => {
  it('flags the transcoded region and offers a repair chain', () => {
    const bundle = analyze('mojibake-mail-forward.txt');
    const moj = bundle.segmented.segments.find((s) => s.kind === 'mojibake');
    expect(moj).toBeDefined();
    expect(moj!.candidates.some((c) => c.kind === 'repair')).toBe(true);
    // The repair should reconstruct readable label text.
    const repair = moj!.candidates.find((c) => c.kind === 'repair');
    expect(repair?.text).toContain('警告');
  });

  it('lowers the repaired region to pending rather than auto-accepting', () => {
    const bundle = analyze('mojibake-mail-forward.txt');
    const moj = bundle.segmented.segments.find((s) => s.kind === 'mojibake')!;
    expect(moj.status).toBe('pending');
    expect(moj.reasons.length).toBeGreaterThan(0);
  });
});

describe('single-encoding samples', () => {
  it('recognises a clean Big5 monograph as confident', () => {
    const bundle = analyze('big5-monograph.txt');
    expect(bundle.segmented.segments).toHaveLength(1);
    const seg = bundle.segmented.segments[0];
    expect(seg.detectedEncoding).toBe('big5');
    const best = seg.candidates.find((c) => c.id === seg.suggestedCandidateId)!;
    expect(best.byteExact).toBe(true);
    expect(seg.status).toBe('confident');
  });

  it('never deletes undecodable bytes in the UTF-8 sample', () => {
    const bytes = sampleBytes('utf8-with-bad-bytes.txt');
    const best = buildCandidates(bytes, 0, DEFAULT_PARAMS, 'text')[0];
    expect(best.encoding).toBe('utf-8');
    // Every invalid slice is represented as an explicit unresolved symbol with
    // its exact byte range; nothing is silently dropped.
    expect(best.unresolved.length).toBeGreaterThanOrEqual(3);
    // The truncated 0xC3 sequence is reported at its exact byte range.
    const c3 = Buffer.from(bytes).indexOf(Buffer.from([0xc3]));
    expect(best.unresolved.some((u) => u.start === c3 && u.end === c3 + 1)).toBe(true);
    // 0xFF and 0xFE must appear in some unresolved symbol's byte hex.
    expect(best.unresolved.some((u) => u.bytesHex.includes('FF'))).toBe(true);
    expect(best.unresolved.some((u) => u.bytesHex.includes('FE'))).toBe(true);
    // The placeholder text preserves byte counts, not deletions.
    expect(best.text).toMatch(/⟦\d+⟧/);
    expect(best.text).toContain('阿莫西林克拉维酸钾片');
  });

  it('keeps GBK table syntax readable for the dosage table', () => {
    const bundle = analyze('gbk-dosage-table.txt');
    const seg = bundle.segmented.segments[0];
    expect(seg.detectedEncoding).toBe('gb18030');
    const best = seg.candidates.find((c) => c.id === seg.suggestedCandidateId)!;
    expect(best.text).toContain('用法用量表');
    expect(best.text).toContain('eGFR');
  });
});

describe('boundary fracture sample', () => {
  it('finds the true GBK/UTF-8 switch point', () => {
    const bytes = sampleBytes('boundary-fracture.txt');
    const segs = segmentFile(bytes, DEFAULT_PARAMS);
    expect(segs).toHaveLength(2);
    // The switch sits inside the unit "mg": the GBK half ends at "...10 m"
    // and the UTF-8 half starts at "g/kg". The optimiser lands at 149.
    expect(Math.abs(segs[1].start - 149)).toBeLessThanOrEqual(4);
  });

  it('holds both segments at pending and caps the combined confidence', () => {
    const bundle = analyze('boundary-fracture.txt');
    expect(bundle.segmented.boundaryReviews.length).toBeGreaterThan(0);
    const review = bundle.segmented.boundaryReviews[0];
    expect(review.severity).toBe('high');
    expect(review.combinedConfidence).toBeLessThan(0.6);
    expect(bundle.segmented.segments.every((s) => s.status === 'pending')).toBe(true);
    expect(
      bundle.segmented.segments.some((s) => s.reasons.some((r) => r.includes('相邻边界'))),
    ).toBe(true);
    expect(review.flags.join(' ')).toMatch(/mg\/kg/);
  });

  it('recommends segmented diagnosis for mixed regions', () => {
    const bundle = analyze('boundary-fracture.txt');
    expect(bundle.recommendedStrategy).toBe('segmented');
  });
});

describe('candidate guarantee', () => {
  it('offers the main direct decodes unless two are textually identical', () => {
    const bytes = sampleBytes('big5-monograph.txt');
    const cands = buildCandidates(bytes, 0, DEFAULT_PARAMS, 'text');
    const directEncodings = cands.filter((c) => c.kind === 'direct').map((c) => c.encoding);
    for (const enc of ['utf-8', 'gb18030', 'big5', 'windows-1252'] as const) {
      expect(directEncodings).toContain(enc);
    }
    // Every retained candidate must have distinct text (no duplicate rows).
    const texts = cands.map((c) => c.text);
    expect(new Set(texts).size).toBe(texts.length);
  });

  it('never returns a candidate with zero glyphs', () => {
    const bytes = sampleBytes('mixed-encoded-label.txt').subarray(0, 200);
    for (const c of buildCandidates(bytes, 0, DEFAULT_PARAMS, 'text')) {
      expect(c.glyphs.length).toBeGreaterThan(0);
    }
  });

  it('renders hex previews with a stable length', () => {
    expect(formatBytes(999)).toBe('999 B');
    expect(formatBytes(2048)).toBe('2.0 KiB');
  });
});
